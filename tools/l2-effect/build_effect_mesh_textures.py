#!/usr/bin/env python3
"""Build mesh -> leaf texture table for L2 effect static meshes.

Inputs are umodel text exports (props.txt) of LineageEffectsStaticmeshes.usx and
LineageEffectsTextures*.utx. Output: TSV "mesh<TAB>slot0tex,slot1tex,..." where each
slot's material chain (Shader/FinalBlend/Combiner/TexPanner/...) is walked to its
first leaf Texture (Diffuse first, then Material/Material1/Material2/SelfIllumination...).

usage: build_effect_mesh_textures.py <mesh_export_dir> <texture_export_dir> <out.tsv>
"""
import os, re, sys

REF = re.compile(r"(\w+)'([^']+)'")
ORDER = ["Diffuse", "Material", "Material1", "SelfIllumination", "Material2",
         "Opacity", "Specular", "FallbackMaterial"]

def index_props(root):
    idx = {}
    for d, _, fs in os.walk(root):
        cls = os.path.basename(d)
        for f in fs:
            if f.endswith(".props.txt"):
                idx[(cls.lower(), f[:-10].lower())] = os.path.join(d, f)
            elif f.endswith(".png"):
                idx[("texture", f[:-4].lower())] = os.path.join(d, f)
    return idx

def leaf(idx, cls, name, depth=0):
    name = name.split(".")[-1]
    if cls.lower() == "texture":
        # Keep the leaf name even if this export lacks the png (it may already
        # be in the project or come from another texture package).
        return name
    if depth > 8:
        return None
    p = idx.get((cls.lower(), name.lower()))
    if not p:
        return None
    props = {}
    for line in open(p, encoding="utf-8", errors="replace"):
        m = re.match(r"\s*(\w+)\s*=\s*(\w+)'([^']+)'", line)
        if m and m.group(1) not in props:
            props[m.group(1)] = (m.group(2), m.group(3))
    for k in ORDER:
        if k in props:
            r = leaf(idx, props[k][0], props[k][1], depth + 1)
            if r:
                return r
    return None

def main():
    mesh_dir, tex_dir, out = sys.argv[1:4]
    idx = index_props(tex_dir)
    rows = []
    for d, _, fs in os.walk(mesh_dir):
        for f in fs:
            if not f.endswith(".props.txt"):
                continue
            mesh = f[:-10]
            text = open(os.path.join(d, f), encoding="utf-8", errors="replace").read()
            slots = []
            for m in re.finditer(r"^\s*Material\s*=\s*(\w+)'([^']+)'", text, re.M):
                t = leaf(idx, m.group(1), m.group(2))
                slots.append(t or "")
            if any(slots):
                rows.append((mesh, slots))
    rows.sort(key=lambda r: r[0].lower())
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# mesh\tslot textures (generated by tools/l2-effect/build_effect_mesh_textures.py)\n")
        for mesh, slots in rows:
            fh.write(mesh + "\t" + ",".join(slots) + "\n")
    print(len(rows), "meshes")

if __name__ == "__main__":
    main()
